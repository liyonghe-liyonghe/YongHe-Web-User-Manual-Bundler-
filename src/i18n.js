  // 语言注册表：value → 语言包
  const PACKS = {
    'zh-CN': EMBEDDED_ZH_CN,
    'zh-TW': EMBEDDED_ZH_TW,
    'zh-HK': EMBEDDED_ZH_HK,
    'en': EMBEDDED_EN,
    'fr': EMBEDDED_FR,
    'ru': EMBEDDED_RU,
    'es': EMBEDDED_ES,
    'pt': EMBEDDED_PT,
    'ar': EMBEDDED_AR,
    'ja': EMBEDDED_JA,
    'ko': EMBEDDED_KO,
    'el': EMBEDDED_EL,
    'de': EMBEDDED_DE,
  };

  function t(key, params) {
    let s = strings[key] || key;
    if (params) {
      s = s.replace(/\{(\w+)\}/g, (m, k) => params[k] !== undefined ? params[k] : m);
    }
    return s;
  }

  function loadLocale(locale) {
    strings = PACKS[locale] || EMBEDDED_ZH_CN;
    currentLocale = PACKS[locale] ? locale : 'zh-CN';
    document.documentElement.lang = currentLocale;
    // 阿拉伯语为 RTL：切换整体排版方向
    document.documentElement.dir = (currentLocale === 'ar') ? 'rtl' : 'ltr';
    try { localStorage.setItem('mb.locale', currentLocale); } catch(e) {}
    reapply();
  }

  function reapply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (strings[key]) el.textContent = strings[key];
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (strings[key]) el.placeholder = strings[key];
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (strings[key]) el.title = strings[key];
    });
    // HTML 内容键（仅用于内置翻译文案，无用户输入）
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (strings[key]) el.innerHTML = strings[key];
    });
  }

  function detectLocale() {
    let saved = null;
    try { saved = localStorage.getItem('mb.locale'); } catch(e) {}
    const raw = saved || (navigator.language || 'zh-CN');
    const l = String(raw).toLowerCase();
    if (PACKS[raw]) return raw; // 精确匹配已注册语言
    if (l.startsWith('zh')) {
      // 港澳先行判断（zh-hant-hk 同时含 hant 与 hk，需先命中 zh-HK）
      if (l.includes('hk') || l.includes('mo')) return 'zh-HK';
      if (l.includes('tw') || l.includes('hant')) return 'zh-TW';
      return 'zh-CN';
    }
    if (l.startsWith('en')) return 'en';
    if (l.startsWith('fr')) return 'fr';
    if (l.startsWith('ru')) return 'ru';
    if (l.startsWith('es')) return 'es';
    if (l.startsWith('pt')) return 'pt';
    if (l.startsWith('ar')) return 'ar';
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('ko')) return 'ko';
    if (l.startsWith('el')) return 'el';
    if (l.startsWith('de')) return 'de';
    return saved && PACKS[saved] ? saved : 'zh-CN';
  }

  function init() {
    loadLocale(detectLocale());
  }

  return {
    t,
    loadLocale,
    init,
    locales: Object.keys(PACKS),
    get locale() { return currentLocale; },
  };
